"""Licence audit of the pinned dependencies, from the metadata of the installed packages (offline).

    .venv/bin/python scripts/audit_licenses.py            # prints a Markdown table; exit 1 if a pin is not installed or looks copyleft/unknown
    .venv/bin/python scripts/audit_licenses.py --write    # also writes THIRD_PARTY_LICENSES.md (table part)

It reads package metadata only (SPDX expression, classifiers, License field). It is a screening aid, not legal advice: compiled wheels can bundle
libraries under additional licences that this metadata does not list."""
import importlib.metadata as md
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRONG_COPYLEFT = re.compile(r"\b(A?GPL|LGPL|SSPL|EUPL|CPAL|OSL)\b", re.I)


def pins() -> list[str]:
    return [ln.split("==")[0].strip() for ln in (ROOT / "requirements.lock").read_text(encoding="utf-8").splitlines() if "==" in ln and not ln.lstrip().startswith("#")]


def licence_of(name: str) -> tuple[str, str]:
    d = md.distribution(name)
    m = d.metadata
    expr = (m.get("License-Expression") or "").strip()
    cls = [c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License")]
    raw = " ".join((m.get("License") or "").split())
    text = expr or ("; ".join(cls) if cls else "") or (raw if len(raw) <= 40 else raw[:37] + "...")
    if raw.lower().startswith("copyright") and cls:
        text = "; ".join(cls)  # long licence text in the field: prefer the classifier
    return d.version, text or "UNKNOWN"


def main() -> int:
    rows, bad = [], []
    for n in pins():
        try:
            v, lic = licence_of(n)
        except md.PackageNotFoundError:
            rows.append((n, "not installed", "UNKNOWN")); bad.append(n); continue
        rows.append((n, v, lic))
        if lic == "UNKNOWN" or STRONG_COPYLEFT.search(lic):
            bad.append(n)
    table = "| Package | Version | Licence (from package metadata) |\n|---|---|---|\n" + "\n".join(f"| {n} | {v} | {l} |" for n, v, l in rows)
    print(table)
    print(f"\n{len(rows)} pins checked; flagged (unknown or strong copyleft): {bad or 'none'}")
    if "--write" in sys.argv:
        (ROOT / "THIRD_PARTY_LICENSES.md").write_text(
            "# THIRD_PARTY_LICENSES.md\n\nScreening of the %d pinned dependencies in `requirements.lock` (generated by `scripts/audit_licenses.py` from installed package metadata, 2026-11-10). "
            "This is a screening aid, not legal advice. Compiled wheels (numpy, scipy, pyarrow, pillow, …) can bundle libraries under additional licences that package metadata does not list; "
            "streamlit's front end bundles JavaScript packages under their own licences.\n\n" % len(rows) + table + "\n\n"
            "## Observations\n- No strong-copyleft (GPL/AGPL/LGPL-family) dependency is declared.\n- `certifi` is MPL-2.0 (file-level copyleft; used unmodified as a library, no obligation beyond keeping its licence with it).\n"
            "- `packaging` is dual Apache-2.0 / BSD-2-Clause; `numpy` lists several permissive licences for bundled parts.\n- `wrapt` is pinned to a development release (`2.6.0.dev1`); consider pinning a stable release when the lockfile is next regenerated.\n"
            "- All declared licences are compatible with distributing this project's original code under MIT.\n\n"
            "## Other material\n| Item | Licence / status |\n|---|---|\n| Project source code (`src/`, `app/`, `tests/`, `scripts/`, docs written for this project) | MIT (see `LICENSE`; pending owner confirmation) |\n"
            "| `data/geo/saudi_adm1_geoboundaries_simplified.geojson` | geoBoundaries gbOpen, upstream © OpenStreetMap contributors, **ODbL 1.0**; attribution in `data/geo/ATTRIBUTION.md` and in the app. Not covered by the MIT licence |\n"
            "| Google Trends exports and everything derived from them | **Not included in this repository.** Not licensed by this project; subject to the Google Terms of Service. Users supply their own exports |\n"
            "| `evidence/` (MOMAH open-data CSV inspected in Phase 1) | Not used by the product; licence not verified; excluded from Git |\n", encoding="utf-8")
        print("written THIRD_PARTY_LICENSES.md")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
