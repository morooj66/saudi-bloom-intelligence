"""Render DATA_VALIDATION_REPORT.md from pipeline outputs (all numbers come from the data files).

Run:  PYTHONPATH=src .venv/bin/python -m bloom.report
"""
from __future__ import annotations

import json

import pandas as pd

from . import config as C

P = C.PROCESSED_DIR


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(lines)


def render() -> str:
    vr = json.loads((P / "validation_results.json").read_text(encoding="utf-8"))
    man = json.loads(C.MANIFEST_JSON.read_text(encoding="utf-8"))
    status = json.loads((P / "phase_a" / "forecast_status.json").read_text(encoding="utf-8"))
    prof = pd.read_parquet(P / "series_profile.parquet")
    out = ["# DATA_VALIDATION_REPORT.md", "",
           "_Generated by `python -m bloom.report` from `data/processed/validation_results.json`. Do not edit by hand._", "",
           "All values are Google Trends **relative search interest**. Not sales, not demand.", "",
           "## 1. Result", "",
           f"- Checks passed: **{vr['summary']['passed']}**; errors: **{vr['summary']['errors']}**; documented warnings: **{vr['summary']['warnings']}**",
           f"- Records: {json.dumps(vr['records'])}", "",
           "## 2. Raw files (manifest)", "",
           _md(pd.DataFrame(man).assign(sha256=lambda d: d["sha256"].str[:12] + "…", terms=lambda d: d["terms"].map(" / ".join))[
               ["file_name", "kind", "comparison_group", "n_data_rows", "terms", "retrieved_date", "sha256"]]), "",
           "Retrieved date is the file's modification time (inferred). Query window of the regional exports: 2021-11-10 → 2026-11-10 (day-first, cross-checked against the weekly grid).", "",
           "## 3. Temporal frequency", "",
           "Weekly, constant 7-day spacing, weeks start on **Sunday**, 262 buckets (2021-11-07 … 2026-11-08), identical grid in groups A and B.",
           "First and last buckets are partial (window starts Wed 2021-11-10; ends Tue 2026-11-10) and are flagged `is_edge_partial_week`; excluded from profiling and modelling.", "",
           "## 4. Missing and censored values", "",
           "| Where | Missing (blank) | Censored (<1) | Reported 0 |", "|---|---|---|---|"]
    for stem, name in (("timeline_groupA_long", "Timeline group A"), ("timeline_groupB_long", "Timeline group B"),
                       ("region_groupA_share", "Regional share (group A)"), ("region_single_term_index", "Regional index (5 single-term files)")):
        d = pd.read_parquet(P / f"{stem}.parquet")
        z = int(d["is_reported_zero"].sum()) if "is_reported_zero" in d else "n/a"
        out.append(f"| {name} | {int(d['is_missing'].sum())} | {int(d['is_censored'].sum())} | {z} |")
    out += ["", "Blank regional cells mean Google reported no data (not zero). Censored cells keep `value = NaN` and `censor_upper_bound = 1`; no imputation is applied anywhere.", ""]
    for stem in ("region_groupA_share", "region_single_term_index"):
        d = pd.read_parquet(P / f"{stem}.parquet")
        for sid, g in d.groupby("scale_id"):
            bits = []
            if g["is_missing"].any():
                bits.append("no data: " + ", ".join(g.loc[g["is_missing"], "region_en"].unique()))
            if g["is_censored"].any():
                bits.append("censored: " + ", ".join(sorted(set(g.loc[g["is_censored"], "term"] + "@" + g.loc[g["is_censored"], "region_en"]))))
            if bits:
                out.append(f"- `{sid}` — " + "; ".join(bits))
    out += ["", "## 5. Geographic coverage", "",
            "All seven regional exports contain exactly the **13 administrative regions** (ISO 3166-2:SA SA-01…SA-14). Names were standardised from labels such as «منطقة الرياض», «القصيم», «مكة المكرمة», «منطقة المدينة». Unknown names raise an error.", "",
            "## 6. Series profile (edge weeks excluded; no modelling)", "",
            _md(prof[["comparison_group", "term", "n_weeks", "censored_n", "reported_zero_share", "median", "max", "acf_lag1", "yoy_corr_52", "candidate_for_forecasting"]].round(2)), "",
            "Candidate rule: median ≥ 10 (integer rounding ≤ ~5% of level), reported-zero share ≤ 10%, censored ≤ 5%.", "",
            "## 7. All checks", "", _md(pd.DataFrame(vr["checks"])[["level", "passed", "name", "scope", "detail"]].assign(passed=lambda d: d["passed"].map({True: "✅", False: "❌"}))), "",
            "## 8. Forecast gate (Phase A)", "", f"```json\n{json.dumps(status['forecast']['gate'], ensure_ascii=False, indent=2)}\n```", "",
            "## 9. Unresolved data-quality issues", "",
            "1. **«شراء ورد»** is 97–98% zero (and ~4–5 censored weeks in group A): unusable as a series.",
            "2. In group A the four commercial terms sit at index 0–15 on a scale set by «ورد», so integer rounding dominates; use group B for commercial analysis.",
            "3. **Regional data are period aggregates**, not time series. The same five regions (Hail, Northern Borders, Najran, Al Bahah, Al Jawf) have no «شراء ورد» value in both the single-term and the group-A share exports.",
            "4. **Group B has no regional export.** Regional shares exist only for the 5-term group A and single-term indices; they cannot be recombined.",
            "5. Only ~5 annual cycles: event-lift and seasonality estimates are indicative, not statistically tested.",
            "6. Query window metadata for timelines is inferred from the weekly grid and the regional exports' headers; retrieval date is the file modification time.",
            "7. Trends is sampled: re-exporting may give slightly different integers; raw files are therefore hash-pinned.",
            "8. The incoming files were found in `~/Downloads`; the requested `incoming_data/` folder did not exist and was created by copying them (originals untouched).", ""]
    return "\n".join(out)


if __name__ == "__main__":
    (C.ROOT / "DATA_VALIDATION_REPORT.md").write_text(render(), encoding="utf-8")
    print("written DATA_VALIDATION_REPORT.md")
